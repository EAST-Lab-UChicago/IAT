#! /bin/bash
# Run from the IAT folder on the web server: sh setup.sh

cd "$(dirname "$0")" || exit 1

# 1) Let the web server write templates and results (without making them world-writable)
echo "Setting up Textfile permissions.."
printf "Web server group [www-data]: "
read -r webgroup
webgroup=${webgroup:-www-data}
if chgrp -R "$webgroup" templates/ 2>/dev/null; then
	chmod -R ug+rwX,o-w templates/
	find templates/ -type d -exec chmod g+s {} +
	echo "templates/ is now writable by group '$webgroup'"
else
	echo "WARNING: could not change group to '$webgroup' (try running with sudo)."
	echo "Falling back to world-writable templates/ (chmod -R 777)."
	chmod -R 777 templates/
fi

# 2) Experimenter login (HTTP Basic Auth, checked by core/auth.php)
default_pw_file="$(dirname "$(pwd)")/.htpasswd-iat"
echo ""
echo "The experimenter page needs a login. The password file should be"
echo "outside the web-accessible folder."
printf "Password file [%s]: " "$default_pw_file"
read -r pw_file
pw_file=${pw_file:-$default_pw_file}
case "$pw_file" in
	*\'*|*\\*) echo "Password file path may not contain quotes or backslashes"; exit 1 ;;
esac
printf "Experimenter username [experimenter]: "
read -r pw_user
pw_user=${pw_user:-experimenter}
case "$pw_user" in
	*:*) echo "Username may not contain ':'"; exit 1 ;;
esac

if command -v htpasswd >/dev/null 2>&1; then
	if [ -f "$pw_file" ]; then
		htpasswd -B "$pw_file" "$pw_user" || exit 1
	else
		htpasswd -B -c "$pw_file" "$pw_user" || exit 1
	fi
elif command -v php >/dev/null 2>&1; then
	stty -echo; printf "New password: "; read -r pw1; echo ""
	printf "Re-type new password: "; read -r pw2; echo ""; stty echo
	if [ "$pw1" != "$pw2" ] || [ -z "$pw1" ]; then
		echo "Passwords do not match"; exit 1
	fi
	hash=$(IAT_PW="$pw1" php -r 'echo password_hash(getenv("IAT_PW"), PASSWORD_BCRYPT);') || exit 1
	touch "$pw_file" && grep -v "^$pw_user:" "$pw_file" > "$pw_file.tmp"
	echo "$pw_user:$hash" >> "$pw_file.tmp" && mv "$pw_file.tmp" "$pw_file"
else
	echo "Neither htpasswd nor php found; cannot create the password file."
	exit 1
fi
chgrp "$webgroup" "$pw_file" 2>/dev/null
chmod 640 "$pw_file"

pw_file_abs="$(cd "$(dirname "$pw_file")" && pwd)/$(basename "$pw_file")"
cat > core/config.php <<EOF
<?php
// Generated by setup.sh
return array('htpasswd' => '$pw_file_abs');
EOF
echo "Saved login settings to core/config.php"
